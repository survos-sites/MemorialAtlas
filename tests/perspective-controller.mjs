import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('../assets/controllers/perspective_controller.js', import.meta.url), 'utf8').replace("import { Controller } from '@hotwired/stimulus';", 'class Controller {}');
const { default: Controller } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const ui = new Controller();
ui.cornersValue = [[0.17,0.11],[0.715,0.008],[0.681,0.728],[0.318,0.81]];
ui.coordinateTargets = Array.from({length:8}, () => ({value:''}));
ui.handleTargets = Array.from({length:4}, () => ({style:{},hidden:true}));
ui.statusTarget = {textContent:''};
ui.polygonTarget = {setAttribute(){}};
ui.imageTarget = {getBoundingClientRect:()=>({left:0,top:0,width:1000,height:500})};
ui.connect();
assert.deepEqual(ui.points(),ui.cornersValue);
assert.equal(ui.handleTargets[1].hidden,false);
ui.nudge({key:'ArrowRight',preventDefault(){},currentTarget:{dataset:{index:'0'}}});
assert.equal(ui.points()[0][0],0.171);
ui.start({preventDefault(){},pointerId:1,currentTarget:{dataset:{index:'0'},setPointerCapture(){}}});
ui.move({clientX:200,clientY:100});
assert.deepEqual(ui.points()[0],[0.2,0.2]);
ui.stop();
ui.move({clientX:400,clientY:400});
assert.deepEqual(ui.points()[0],[0.2,0.2]);
ui.reset();
assert.equal(ui.handleTargets.every(h=>h.hidden),true);
console.log('Corner editor: saved points, keyboard nudging, dragging and reset passed.');
